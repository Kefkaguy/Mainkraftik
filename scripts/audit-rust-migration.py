"""Reproducible source/dependency/route inventory; never imports a trading worker."""
import ast
import hashlib
import json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'reports/rust-migration'
TARGETS={
 'paperpilot':{
  'experiment':'engine,allocation,learning,db,broker,market', 'broker':'broker', 'config':'config',
  'db':'db', 'service':'api::paper', 'strategy':'features,models,calendar',
  'discovery':'news', 'sentiment':'sentiment', 'universe':'news,db',
  'data':'market,storage', 'engine':'legacy_paper', 'outcomes':'reporting',
  'daily_report':'reporting', 'reporting':'reporting', 'strategy_execution':'legacy_paper',
  'decision_trace':'trace', 'scan_models':'models::scan',
 },
 'intelligence':{
  'main':'api::research', 'security':'auth', 'portable_models':'models',
  'calendar':'calendar', 'db':'db', 'config':'config', 'jobs':'jobs',
  'providers':'market,news,financials', 'storage':'storage', 'financials':'financials',
  'forecasting':'research::forecasting', 'vision':'vision', 'vision_gateway':'vision',
 },
}


def target(path):
    if 'tests' in path.parts:return 'Rust integration/parity tests'
    if path.parts[0]=='scripts':return 'migration/research/operations CLI (original retained as evidence)'
    if path.parts[0]=='workers':return 'sentiment or jobs'
    package=path.parent.name;name=path.stem
    if package=='chart_intelligence':return 'research::'+name
    return TARGETS.get(package,{}).get(name,'research::'+name)


def main():
    OUT.mkdir(parents=True,exist_ok=True)
    modules=[];routes=[]
    for root in ('apps/api','workers','scripts'):
        for absolute in sorted((ROOT/root).rglob('*.py')):
            if '__pycache__' in absolute.parts:continue
            path=absolute.relative_to(ROOT);source=absolute.read_text(encoding='utf-8-sig');tree=ast.parse(source)
            row={'path':path.as_posix(),'sha256':hashlib.sha256(absolute.read_bytes()).hexdigest(),
                 'lines':len(source.splitlines()),'test':'tests' in path.parts,'imports':[],
                 'definitions':[],'rust_target':target(path),'status':'PENDING'}
            prefixes={}
            for node in ast.walk(tree):
                if isinstance(node,ast.Assign) and isinstance(node.value,ast.Call):
                    for kw in node.value.keywords:
                        if kw.arg=='prefix' and isinstance(kw.value,ast.Constant):
                            for obj in node.targets:
                                if isinstance(obj,ast.Name):prefixes[obj.id]=kw.value.value
                if isinstance(node,ast.Import):row['imports'].extend(n.name for n in node.names)
                if isinstance(node,ast.ImportFrom):row['imports'].append(node.module or '')
                if isinstance(node,(ast.FunctionDef,ast.AsyncFunctionDef,ast.ClassDef)):
                    row['definitions'].append({'name':node.name,'line':node.lineno,'kind':type(node).__name__})
                    for dec in getattr(node,'decorator_list',[]):
                        if isinstance(dec,ast.Call) and isinstance(dec.func,ast.Attribute) and dec.func.attr in ('get','post','put','delete','patch') and dec.args and isinstance(dec.args[0],ast.Constant):
                            router=dec.func.value.id if isinstance(dec.func.value,ast.Name) else ''
                            routes.append({'module':path.as_posix(),'method':dec.func.attr.upper(),
                                'path':prefixes.get(router,'')+dec.args[0].value,'handler':node.name,'line':node.lineno})
            row['imports']=sorted(set(row['imports']));modules.append(row)
    schemas={p.relative_to(ROOT).as_posix():hashlib.sha256(p.read_bytes()).hexdigest()
             for root in ('database','apps/api') for p in (ROOT/root).rglob('*.sql')}
    report={'version':2,'modules':modules,'routes':routes,'schemas':schemas,
            'total_python_lines':sum(r['lines'] for r in modules),'migration_complete':False}
    (OUT/'source-audit.json').write_text(json.dumps(report,indent=2))
    lines=['# Complete Python → Rust migration map','','Generated by `scripts/audit-rust-migration.py`. PENDING is not implemented or verified.',
           '', '| Python module | Lines | Rust destination | State |','|---|---:|---|---|']
    lines.extend(f"| `{r['path']}` | {r['lines']} | `{r['rust_target']}` | {r['status']} |" for r in modules)
    lines+=['','## API contracts','','| Source | Method | Path |','|---|---|---|']
    lines.extend(f"| `{r['module']}` | {r['method']} | `{r['path']}` |" for r in routes)
    (OUT/'migration-map.md').write_text('\n'.join(lines)+'\n',encoding='utf-8')
    preserved={p.relative_to(ROOT).as_posix():hashlib.sha256(p.read_bytes()).hexdigest()
               for name in ('phase7','phase8') for p in (ROOT/'reports'/name).rglob('*') if p.is_file()}
    boundary=OUT/'research-preservation.json'
    if boundary.exists():assert json.loads(boundary.read_text())==preserved,'Frozen research inventory changed'
    else:boundary.write_text(json.dumps(preserved,indent=2))
    print(json.dumps({'modules':len(modules),'routes':len(routes),'lines':report['total_python_lines'],'frozen_research_files':len(preserved)}))


if __name__=='__main__':main()
